import { access, readFile, writeFile } from "node:fs/promises";
import { constants } from "node:fs";
import { dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { exists, readRuntimeConfig } from "./report-runtime-config.mjs";

const skillRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const repoFlagIndex = process.argv.indexOf("--repo");
const repoRoot = resolve(repoFlagIndex >= 0 && process.argv[repoFlagIndex + 1]
  ? process.argv[repoFlagIndex + 1]
  : resolve(skillRoot, "../.."));
const reportRoot = resolve(repoRoot, "report");
const targetPath = resolve(reportRoot, "report-embedded-data.js");
const checkOnly = process.argv.includes("--check");
const DATA_KEYS = [
  "analysis",
  "performance",
  "timeline",
  "trace",
  "bindings",
  "operatorDetails",
  "architecture",
  "overlay",
  "hbm",
  "findings",
  "expertInventory",
];

const { config: runtimeConfig, defaultedOptionalKeys } = await readRuntimeConfig(reportRoot);
const payload = {};

for (const key of DATA_KEYS) {
  const configuredPath = runtimeConfig[key];
  if (typeof configuredPath !== "string" || !configuredPath) {
    throw new Error(`Missing ReportRuntimeConfig.${key}`);
  }
  const sourcePath = resolve(reportRoot, configuredPath);
  const repoRelativePath = relative(repoRoot, sourcePath);
  if (repoRelativePath.startsWith("..")) {
    throw new Error(`Embedded data source escapes report repository: ${configuredPath}`);
  }
  if (!(await exists(sourcePath)) && defaultedOptionalKeys.includes(key)) {
    payload[key] = key === "findings"
      ? { schema_version: 1, advisory_only: true, nodes: [] }
      : key === "expertInventory"
        ? { schema_version: 1, available: false }
        : key === "operatorDetails"
          ? { schema_version: 1, source: null, count: 0, details: {} }
          : { schema_version: "1.0", bandwidth: { points: [] }, occupancy: { points: [] } };
    continue;
  }
  payload[key] = JSON.parse(await readFile(sourcePath, "utf8"));
}

const generatedSource = [
  "/* Generated by build-embedded-data.mjs. Do not edit directly. */",
  `window.ReportEmbeddedData = ${JSON.stringify(payload)};`,
  "",
].join("\n");

if (checkOnly) {
  await access(targetPath, constants.F_OK);
  const currentSource = await readFile(targetPath, "utf8");
  if (currentSource !== generatedSource) {
    throw new Error(`Stale standalone data bundle: ${targetPath}`);
  }
  console.log(`OK   standalone data bundle is current: ${targetPath}`);
} else {
  await writeFile(targetPath, generatedSource);
  console.log(`WROTE ${targetPath}`);
}
